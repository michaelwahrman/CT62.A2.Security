"""Run the data check and the in-page self-test (index.html?selftest=1) headless; write docs/TEST_REPORT.md.
Usage:  python3 scripts/run_selftest.py        (exit code 1 on any failure)"""
import html, json, re, subprocess, sys
from headless import ROOT, run

data = subprocess.run([sys.executable, str(ROOT / "scripts" / "bundle_data.py")], capture_output=True, text=True)
r = run(["--dump-dom"], "selftest=1&play=0", budget=20000)
m = re.search(r'<pre id="selftest"[^>]*>(.*?)</pre>', r.stdout, re.S)
if not m:
    print(r.stdout[-2000:], r.stderr[-2000:]); raise SystemExit("self-test output not found in page")
res = json.loads(html.unescape(m.group(1)))
ok = res["pass"] and data.returncode == 0
P = lambda b: "**PASS**" if b else "**FAIL**"

L = ["# CT62.A1 Security - test report", "",
     f"Generated by `scripts/run_selftest.py` at {res['when']} (browser time).", "",
     f"Overall: {P(ok)}", "",
     "This is a prototype test: it shows the program does what it was written to do. It does **not** show that a real",
     "camera or face-recognition system would behave this way. See README > Assumptions.", "",
     "## 1. Data cross-reference check (`scripts/bundle_data.py`)", "", f"{P(data.returncode == 0)} - `{data.stdout.strip() or data.stderr.strip()}`", "",
     "## 2. Camera model checks", "", "| Check | Result | Detail |", "|---|---|---|"]
L += [f"| {c['name']} | {P(c['pass'])} | {c['detail']} |" for c in res["checks"]]
L += ["", "## 3. Scenarios x 5 random seeds", "",
      "Each run must reach the expected highest alert level and fire exactly the expected rules"
      " (the arrivals scenario must also recognise every enrolled person).", "",
      "| Scenario | Seed | Result | Level (expected) | Rules fired | First alert at (s) | Camera frames | Face matches |", "|---|---|---|---|---|---|---|---|"]
L += [f"| {x['scenario']} | {x['seed']} | {P(x['pass'])} | {x['level']} ({x['expectLevel']}) | {x['fired'] or '-'} | {x['firstAlertAt']} | {x['frames']} | {x['matches']} |" for x in res["runs"]]
L += ["", "Failures, if any, list the expected rules here:", ""]
L += [f"- {x['scenario']} seed {x['seed']}: expected `{x['expected']}`, unrecognised enrolled: {x['unrecognisedEnrolled'] or 'none'}" for x in res["runs"] if not x["pass"]] or ["- none"]
(ROOT / "docs" / "TEST_REPORT.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print(f"self-test {'PASS' if ok else 'FAIL'}: {sum(c['pass'] for c in res['checks'])}/{len(res['checks'])} checks, {sum(x['pass'] for x in res['runs'])}/{len(res['runs'])} runs -> docs/TEST_REPORT.md")
sys.exit(0 if ok else 1)
