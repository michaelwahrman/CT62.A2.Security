"""CT62.A1 - check data/*.json for broken cross-references, then write data/bundle.js
(the same data as a <script>, so index.html also works when opened straight from disk via file://).
Standard library only.  Usage:  python3 scripts/bundle_data.py      (exit code 1 if a check fails)"""
import json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FILES = ["venue", "people", "duty", "alerts", "scenarios"]
db = {k: json.loads((ROOT / "data" / f"{k}.json").read_text(encoding="utf-8")) for k in FILES}

errors = []
v, ppl = db["venue"], {p["id"]: p for p in db["people"]["people"]}
zones = {z["id"] for z in v["zones"]}
wps = set(v["waypoints"])
contacts = {c["id"] for c in db["duty"]["contacts"]}
levels = {l["level"] for l in db["alerts"]["levels"]}

if len(ppl) != len(db["people"]["people"]):
    errors.append("duplicate person id")
for c in v["cameras"]:
    if c["zone"] not in zones: errors.append(f"camera {c['id']}: unknown zone {c['zone']}")
    if not (10 <= c["hfov"] <= 179): errors.append(f"camera {c['id']}: hfov out of range")
for p in ppl.values():
    for z in p["zones"]:
        if z != "*" and z not in zones: errors.append(f"person {p['id']}: unknown zone {z}")
    if p["category"] not in ("member", "staff", "security", "threat", "not_trusted"): errors.append(f"person {p['id']}: bad category")
    if not p["photos"]: errors.append(f"person {p['id']}: no photos")
for o in db["duty"]["officers"]:
    if o["personId"] and o["personId"] not in ppl: errors.append(f"officer {o['id']}: unknown person {o['personId']}")
for l in db["alerts"]["levels"]:
    for n in l["notify"]:
        if n not in ("onduty", "oncall") and n not in contacts: errors.append(f"level {l['level']}: unknown contact {n}")
for r in db["alerts"]["rules"]:
    if r["level"] not in levels: errors.append(f"rule {r['id']}: unknown level")
for s in db["scenarios"]["scenarios"]:
    for i, a in enumerate(s["agents"]):
        if a["person"] and a["person"] not in ppl: errors.append(f"scenario {s['id']} agent {i}: unknown person {a['person']}")
        for st in a["route"]:
            w = st if isinstance(st, str) else st["wp"]
            if w not in wps: errors.append(f"scenario {s['id']} agent {i}: unknown waypoint {w}")

if errors:
    print("DATA CHECK FAILED:"); [print("  -", e) for e in errors]; sys.exit(1)
out = ROOT / "data" / "bundle.js"
out.write_text("// generated by scripts/bundle_data.py from data/*.json - edit the .json files, not this\n"
               "window.CT62_BUNDLE = " + json.dumps(db, separators=(",", ":")) + ";\n", encoding="utf-8")
print(f"data check PASS ({len(ppl)} people, {len(v['cameras'])} cameras, {len(db['scenarios']['scenarios'])} scenarios); wrote {out.name} ({out.stat().st_size} bytes)")
